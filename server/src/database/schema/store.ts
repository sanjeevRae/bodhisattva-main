/**
 * Ecommerce tables — DATABASE_DESIGN.md §9.1 (`product_categories`),
 * §9.2 (`products`), §9.3 (`product_images`), §9.4 (`product_variants`),
 * §9.5 (`inventory_movements`), §9.6 (`carts`, `cart_items`),
 * §9.7 (`customer_addresses`), §9.8 (`orders`), §9.9 (`order_items`),
 * §9.10 (`order_status_history`). Invoice tables (§10) are Phase 7.
 *
 * Global conventions (§2): BIGINT UNSIGNED surrogate PKs, DATETIME(3)
 * UTC timestamps, snake_case names, `idx_`/`uq_`/`fk_` constraint
 * naming. ON DELETE behaviour is per §9 (RESTRICT almost everywhere;
 * CASCADE only for `product_images.product_id`,
 * `product_variants.product_id` and `cart_items.cart_id`). Money is
 * DECIMAL(12,2) authored with drizzle `mode: 'string'` — decimal
 * strings end to end, never binary floating point (shared money
 * helpers convert to integer paisa for arithmetic). `updated_at`
 * follows the project convention: DB default CURRENT_TIMESTAMP(3),
 * maintained app-side via $onUpdate (the live DDL of migrations
 * 0000–0006 carries no ON UPDATE clause; see museum.ts header).
 *
 * RECORDED DEVIATION 1 — product images (Phase 6, same BD-2 bridge as
 * Phase 5's museum tables): the Gift Shop's imagery is remote Unsplash
 * URLs pending the client's media decision, so `product_images.media_id`
 * is NULLABLE here (§9.3 has it NOT NULL) and the table carries an
 * additional `image_url VARCHAR(1000) NULL` for the legacy remote URL.
 * The alt text lives in §9.3's own `alt_text` column — it plays the
 * `image_alt` role of the museum pattern, so no second alt column is
 * added. Payloads resolve a single {url, alt}: the media asset when
 * `media_id` is set, otherwise `image_url`/`alt_text`. When BD-2 is
 * decided, the URLs are migrated into media assets, `media_id` is
 * backfilled and made NOT NULL, and `image_url` is retired.
 *
 * RECORDED DEVIATION 2 — stock reservations (Phase 0 amendment A1,
 * superseding §9.5's D3 note "stock deducted at order creation"):
 * `inventory_movements.movement_type` gains RESERVE and RELEASE.
 * Checkout does NOT deduct on-hand stock when an order is placed; it
 * reserves. The ledger therefore tracks two balances:
 *   - on-hand (`products.stock_qty` / `product_variants.stock_qty`,
 *     the cached balance): moved by OPENING, PURCHASE, ADJUSTMENT_IN,
 *     ADJUSTMENT_OUT, ORDER_DEDUCT, ORDER_RESTORE and CORRECTION. For
 *     these movements `quantity` is the signed delta applied to
 *     stock_qty and `balance_after` is stock_qty immediately after.
 *   - reserved (derived, never cached): RESERVE carries
 *     `quantity = -qty` (units leave the available pool; stock_qty is
 *     unchanged) and RELEASE carries `quantity = +qty`; for these two
 *     types `balance_after` is the AVAILABLE balance immediately
 *     after. Availability is always computable from the ledger:
 *       available = stock_qty + SUM(quantity of RESERVE/RELEASE rows)
 *     (the sum is ≤ 0). Cancellation of a reserved order writes a
 *     RELEASE (+qty). Fulfilment of a reserved order writes, in one
 *     transaction, ORDER_DEDUCT (-qty against stock_qty) AND a
 *     RELEASE (+qty closing the reservation), so the formula holds at
 *     every step and stock can never be double-counted. §9.5's other
 *     ledger rules stand unchanged: the inventory service is the only
 *     writer, deductions use the conditional-update form, history is
 *     append-only, and the reconciliation check compares the on-hand
 *     movement sum against stock_qty (RESERVE/RELEASE rows are
 *     excluded from that sum by type).
 *
 * Amendment A2 — order idempotency: NO schema change was needed.
 * §9.8 already carries `orders.idempotency_key` with
 * `uq_orders_idempotency (user_id, idempotency_key)`; it is authored
 * below exactly as designed.
 *
 * Two service-level notes the schema cannot express:
 *  - `order_number` (§9.8) is generated by the orders service from the
 *    §10.2 sequence pattern (its own counter scope); no §9 table is
 *    involved, so nothing is authored here for it.
 *  - `uq_cart_items_line (cart_id, product_id, variant_id)`: MySQL
 *    treats NULLs as distinct in unique indexes, so two lines for the
 *    same product with `variant_id` NULL do not collide at the DB
 *    level — the cart service must upsert variant-less lines itself
 *    (the design's key is authored as specified regardless).
 */

